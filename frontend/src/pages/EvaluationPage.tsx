import { useEffect, useState } from "react";
import { Bar, BarChart, CartesianGrid, Legend, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { getEvaluation } from "../api";
import type { Evaluation, Metrics } from "../types";

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const ci = (m: Metrics, key: string) => (m.ci95?.[key] ? ` (${pct(m.ci95[key][0])}–${pct(m.ci95[key][1])})` : "");
const money = (x: number | null | undefined) => (x === null || x === undefined ? "n/a" : `$${x.toFixed(4)}`);

export default function EvaluationPage() {
  const [data, setData] = useState<Evaluation | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    getEvaluation().then(setData).catch((e: Error) => setError(e.message));
  }, []);

  if (error) return <div className="card"><div className="alert warn" role="alert">{error}</div></div>;
  if (!data) return <div className="card"><p className="hint">Loading evaluation results…</p></div>;

  const metricChart = data.models.map((m) => ({
    name: m.name,
    Accuracy: +(m.as_generated.accuracy * 100).toFixed(1),
    Precision: +(m.as_generated.precision * 100).toFixed(1),
    Recall: +(m.as_generated.recall * 100).toFixed(1),
    "F1-score": +(m.as_generated.f1 * 100).toFixed(1),
  }));
  const latencyChart = data.models.map((m) => ({ name: `${m.name} [${m.hardware ?? "unknown hardware"}]`, "Median latency (s)": m.latency.median_s ?? 0 }));

  return (
    <div className="stack">
      <section className="card">
        <h2>Model comparison</h2>
        <p className="hint">
          Same {data.test_examples.n} held-out test examples for all three models ({data.test_examples.anomalies} anomalies,
          natural class ratio). Scores are as generated by each model; 95% bootstrap intervals in brackets.
        </p>
        <div className="scroll">
          <table>
            <thead>
              <tr><th>Model</th><th>Accuracy</th><th>Precision</th><th>Recall</th><th>F1</th><th>Unparseable</th></tr>
            </thead>
            <tbody>
              {data.models.map((m) => (
                <tr key={m.key}>
                  <td>{m.name}</td>
                  <td>{pct(m.as_generated.accuracy)}{ci(m.as_generated, "accuracy")}</td>
                  <td>{pct(m.as_generated.precision)}{ci(m.as_generated, "precision")}</td>
                  <td>{pct(m.as_generated.recall)}{ci(m.as_generated, "recall")}</td>
                  <td>{pct(m.as_generated.f1)}{ci(m.as_generated, "f1")}</td>
                  <td>{m.unparseable.count} ({pct(m.unparseable.rate)})</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <div className="chart">
          <ResponsiveContainer width="100%" height={300}>
            <BarChart data={metricChart}>
              <CartesianGrid strokeDasharray="3 3" />
              <XAxis dataKey="name" />
              <YAxis domain={[0, 100]} unit="%" />
              <Tooltip />
              <Legend />
              <Bar dataKey="Accuracy" fill="#6366f1" />
              <Bar dataKey="Precision" fill="#06b6d4" />
              <Bar dataKey="Recall" fill="#f59e0b" />
              <Bar dataKey="F1-score" fill="#10b981" />
            </BarChart>
          </ResponsiveContainer>
        </div>
      </section>

      {data.models.some((m) => m.scored_at_tuned_threshold) && (
        <section className="card">
          <h2>Fine-tuned model: default vs tuned threshold</h2>
          <p className="hint">Threshold tuned on validation data only{data.threshold ? ` (selected: ${data.threshold.threshold})` : ""}.</p>
          <table>
            <thead><tr><th>Threshold</th><th>Accuracy</th><th>Precision</th><th>Recall</th><th>F1</th></tr></thead>
            <tbody>
              {data.models.filter((m) => m.key === "finetuned").flatMap((m) => [
                { label: "0.5 (default)", v: m["scored_at_0.5"] },
                { label: `${data.threshold?.threshold} (tuned)`, v: m.scored_at_tuned_threshold },
              ]).map((row) => row.v && (
                <tr key={row.label}>
                  <td>{row.label}</td><td>{pct(row.v.accuracy)}</td><td>{pct(row.v.precision)}</td><td>{pct(row.v.recall)}</td><td>{pct(row.v.f1)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}

      <section className="card">
        <h2>Confusion matrices</h2>
        <div className="matrices">
          {data.models.map((m) => (
            <div key={m.key}>
              <h3>{m.name}</h3>
              <table className="matrix">
                <thead><tr><th></th><th>Pred. Normal</th><th>Pred. Anomaly</th></tr></thead>
                <tbody>
                  <tr><th>True Normal</th><td>{m.as_generated.confusion.tn}</td><td>{m.as_generated.confusion.fp}</td></tr>
                  <tr><th>True Anomaly</th><td>{m.as_generated.confusion.fn}</td><td>{m.as_generated.confusion.tp}</td></tr>
                </tbody>
              </table>
            </div>
          ))}
        </div>
      </section>

      <section className="card">
        <h2>Latency and cost</h2>
        <p className="hint">Latencies come from different hardware (Colab GPU, API) and are not directly comparable.</p>
        <div className="chart">
          <ResponsiveContainer width="100%" height={260}>
            <BarChart data={latencyChart}>
              <CartesianGrid strokeDasharray="3 3" />
              <XAxis dataKey="name" />
              <YAxis />
              <Tooltip />
              <Bar dataKey="Median latency (s)" fill="#6366f1" />
            </BarChart>
          </ResponsiveContainer>
        </div>
        <table>
          <thead><tr><th>Model</th><th>Hardware</th><th>Mean / p95 latency</th><th>Estimated cost per 1000</th><th>Actual spend</th></tr></thead>
          <tbody>
            {data.models.map((m) => (
              <tr key={m.key}>
                <td>{m.name}</td>
                <td>{m.hardware ?? "n/a"}</td>
                <td>{m.latency.mean_s ?? "n/a"} s / {m.latency.p95_s ?? "n/a"} s</td>
                <td>{money(m.cost.estimated_commercial_usd_per_1000)}</td>
                <td>{money(m.cost.actual_spend_usd)}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <ul className="hint">
          {data.models.map((m) => <li key={m.key}><b>{m.name}:</b> {m.cost.assumptions}</li>)}
        </ul>
      </section>

      <section className="card">
        <h2>Notes</h2>
        <ul className="hint">{data.notes.map((n, i) => <li key={i}>{n}</li>)}</ul>
        <p className="hint">Generated {data.generated_at}.</p>
      </section>
    </div>
  );
}